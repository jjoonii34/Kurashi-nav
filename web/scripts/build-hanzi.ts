// Generates geo/hanzi.ts: how the kanji used in Japanese place names are
// written in simplified and traditional Chinese, from the OpenCC character
// tables (Apache-2.0).
//
//   node scripts/build-hanzi.ts <JPShinjitaiCharacters.txt> <TSCharacters.txt>
//
// Both files: https://github.com/BYVoid/OpenCC/tree/master/data/dictionary
// Run it after build-towns.ts: it only keeps characters that appear in the
// bundled boundary and town files.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const OUTPUT = "geo/hanzi.ts";
const HAN = /\p{Script=Han}/u;

// "key<TAB>value value …" lines.
function table(path: string): Map<string, string[]> {
  const out = new Map<string, string[]>();
  for (const line of readFileSync(path, "utf8").split("\n")) {
    const [key, values] = line.split("\t");
    if (!line.startsWith("#") && values !== undefined) {
      out.set(key, values.trim().split(" "));
    }
  }
  return out;
}

const [shinjitaiPath, simplifiedPath] = process.argv.slice(2);
if (simplifiedPath === undefined) {
  throw new Error(
    "usage: node scripts/build-hanzi.ts <JPShinjitaiCharacters.txt> <TSCharacters.txt>",
  );
}
const toTraditional = table(shinjitaiPath);
const toSimplified = table(simplifiedPath);

const used = new Set<string>();
const files = [
  "public/data/municipalities-2021.topo.json",
  ...readdirSync("public/data/towns").map((f) => `public/data/towns/${f}`),
];
for (const file of files) {
  for (const char of readFileSync(file, "utf8")) {
    if (HAN.test(char)) {
      used.add(char);
    }
  }
}

let traditionalPairs = "";
let simplifiedPairs = "";
const traditionalOnly = new Set<string>();
const simplifiedOnly = new Set<string>();
for (const japanese of [...used].sort()) {
  // A kanji can have several old forms (渋: 澁, 澀); the one Chinese also
  // simplifies is the one in everyday use.
  const forms = toTraditional.get(japanese) ?? [japanese];
  const traditional = forms.find((form) => toSimplified.has(form)) ?? forms[0];
  const simplified = toSimplified.get(traditional)?.[0] ?? traditional;
  // One UTF-16 unit per character keeps the pair strings easy to read back.
  if (japanese.length + traditional.length + simplified.length !== 3) {
    continue;
  }
  if (traditional !== japanese) {
    traditionalPairs += japanese + traditional;
    if (!used.has(traditional)) {
      traditionalOnly.add(traditional);
    }
  }
  if (simplified !== japanese) {
    simplifiedPairs += japanese + simplified;
    if (!used.has(simplified)) {
      simplifiedOnly.add(simplified);
    }
  }
}

writeFileSync(
  OUTPUT,
  `// Generated by scripts/build-hanzi.ts from the OpenCC character tables
// (Apache-2.0). Do not edit by hand.

// Pairs of [Japanese kanji][Chinese form], for kanji used in place names.
export const JAPANESE_TO_SIMPLIFIED =
  ${JSON.stringify(simplifiedPairs)};
export const JAPANESE_TO_TRADITIONAL =
  ${JSON.stringify(traditionalPairs)};

// Chinese forms that no Japanese place name uses: typing one of them means
// the query is Chinese.
export const SIMPLIFIED_ONLY =
  ${JSON.stringify([...simplifiedOnly].sort().join(""))};
export const TRADITIONAL_ONLY =
  ${JSON.stringify([...traditionalOnly].sort().join(""))};
`,
);
console.log(
  `${used.size} kanji, ${simplifiedPairs.length / 2} simplified, ` +
    `${traditionalPairs.length / 2} traditional → ${OUTPUT}`,
);
